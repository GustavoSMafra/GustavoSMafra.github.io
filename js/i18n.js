window.I18N = (() => {
    const SUPPORTED = ["en", "pt"];
    const englishFromPage = {};

    function initialLang() {
        const fromUrl = new URLSearchParams(location.search).get("lang");
        if (SUPPORTED.includes(fromUrl)) return fromUrl;
        try {
            const saved = localStorage.getItem("gm-lang");
            if (SUPPORTED.includes(saved)) return saved;
        } catch { /* storage unavailable */ }
        return "en";
    }

    let lang = initialLang();

    // Keep the English text that is written in the HTML.
    document.querySelectorAll("[data-i18n]").forEach((el) => {
        englishFromPage[el.dataset.i18n] ??= el.innerHTML.trim().replace(/\s+/g, " ");
    });
    document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
        el.dataset.i18nAttr.split(",").forEach((pair) => {
            const [attr, key] = pair.split(":");
            englishFromPage[key] ??= el.getAttribute(attr);
        });
    });

    function t(key) {
        return window.STRINGS[lang][key] ?? window.STRINGS.en[key] ?? englishFromPage[key] ?? key;
    }

    function apply() {
        document.documentElement.lang = lang === "pt" ? "pt-BR" : "en";
        document.querySelectorAll("[data-i18n]").forEach((el) => { el.innerHTML = t(el.dataset.i18n); });
        document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
            el.dataset.i18nAttr.split(",").forEach((pair) => {
                const [attr, key] = pair.split(":");
                el.setAttribute(attr, t(key));
            });
        });
        document.querySelectorAll("[data-lang]").forEach((el) => el.classList.toggle("active", el.dataset.lang === lang));
    }

    function set(next) {
        if (!SUPPORTED.includes(next) || next === lang) return;
        lang = next;
        try { localStorage.setItem("gm-lang", lang); } catch { /* storage unavailable */ }
        apply();
        document.dispatchEvent(new CustomEvent("langchange", { detail: lang }));
    }

    apply();
    return { t, set, get lang() { return lang; } };
})();
